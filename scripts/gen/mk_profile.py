def emit(s): out.append(s)

def check(opts, kinds):
    """Every option with a value has a kind (a list of values, a kind, "files" or "none")."""
    for n, a, _ in opts:
        if a and not any(x in kinds for x in n.replace(",", " ").split()):
            sys.exit(f"no kind for {n} {a}")

def body(opts, values, args, extra="", indent=12):
    check(opts, values)
    tail = " " * (indent - 4) + f"args: {args},\n" + extra
    return h.emit(opts, indent, values, tail.rstrip("\n"))

# the commands, with the name of their function
progs = {}

def fn(cmd, b):
    name = re.sub(r"\W", "_", cmd.removesuffix(".py")).lower()
    progs[cmd] = name
    emit(f"fn {name}() {{\n    #{{\n{b}\n    }}\n}}\n")

def argparse_fn(cmd, actions, table, args, default=None):
    fn(cmd, gen.emit_argparse(actions, kinds(table, default), 12, f"        args: {args},"))

def getopts(text, prog, n):
    """`Usage: bracken -v -d MY_DB -i INPUT ...`, then `MY_DB    location of Kraken database`: the option of each
    value name is in the usage line (bracken, bracken-build)."""
    usage = re.search(rf"^Usage: {prog} (.*)$", text, re.M).group(1)
    names = dict((v, n) for n, v in re.findall(r"(-\w) ([A-Z_]+)", usage))
    rows = []
    for m in re.finditer(r"^  (-v|[A-Z_]+)\s+(.*)$", text, re.M):
        v, d = m.groups()
        rows.append(("-v", "", h.clean(d)) if v == "-v" else (names[v], v, h.clean(d)))
    assert len(rows) == n, rows
    return rows

def tidy(opts, fix={}):
    """The descriptions of `fix` instead of the help's, by the option's first name."""
    return [(n, a, fix.get(n.split(",")[0], d)) for n, a, d in opts]

def short_metavars(actions):
    """A long list of choices as the value name of the option (`--stat AVG_G|AVG_L|...`): its dest instead."""
    for a in actions:
        if a["choices"] and not a["metavar"] and len("|".join(a["choices"])) > 30:
            a["metavar"] = a["dest"].upper()

def kinds(table, default=None):
    """kind_of for gen.emit_argparse: the choices, or the kind in `table` by one of the option's names (or
    `default`)."""
    def kind_of(names, mv, choices):
        if choices:
            return L(*choices)
        for n in names:
            if n in table:
                return table[n]
        if default:
            return default
        sys.exit(f"no kind for {names} {mv}")
    return kind_of

