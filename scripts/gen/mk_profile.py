def motus_opts(text):
    rows, choices = [], {}
    for m in re.finditer(r"^ {8}(-[\w-]+(?:, --[\w-]+)?)(?:  (\S[^\n]*))?\n((?: {12}\S[^\n]*\n?)*)", text, re.M):
        n, a, d = m.group(1), (m.group(2) or "").split(" [")[0].split("/")[0], m.group(3)
        c = re.search(r"(?:Choices: |Choose (?:from|any combination of) )\[([^\]]*)\]", d)
        if c:
            choices[n.split(",")[0]] = [x.strip() for x in c.group(1).split(",")]
        d = re.sub(r"\s*\[required[^\]]*\]|\s*\(default: [^)]*\)|\s*Choices: \[[^\]]*\]", "", " ".join(d.split()))
        rows.append((n, a, MOTUS_FIX.get(n.split(",")[0], h.clean(d))))
    return [("-h, --help", "", "show the help of the command")] + rows, choices

