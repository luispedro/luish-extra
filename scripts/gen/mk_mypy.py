"""Generates ../../complete/dev/mypy.rhai for mypy, from its argparse parser at a pinned version, with its error codes
and the Python versions it checks for (mypy_info.py).

    python3 scripts/gen/mk_mypy.py
"""
import re
import gen

PKG = "mypy=2.3.1"
CHAN = "-c conda-forge"
K = lambda n: f'own("kinds:{n}")'
NONE, FILES, DIRS = '"none"', '"files"', '"dirs"'

info = gen.dump(PKG, "mypy_info.py", "", CHAN)
CODES = 'own("mypy:error_codes")'

# The values of the options that take one and have no choices, by their first name (the generator stops at one that
# isn't here).
KINDS = {
    "--config-file": FILES, "--python-executable": FILES,
    "--python-version": "[" + ", ".join(f'"{v}"' for v in info["versions"]) + "]",
    "--platform": '["linux", "darwin", "win32"]', "--always-true": NONE, "--always-false": NONE,
    "--untyped-calls-exclude": NONE, "--deprecated-calls-exclude": NONE,
    "--disable-error-code": CODES, "--enable-error-code": CODES,
    "--cache-dir": DIRS, "--custom-typing-module": NONE, "--custom-typeshed-dir": DIRS, "--shadow-file": FILES,
    "-n": NONE, "--junit-xml": FILES, "--find-occurrences": NONE, "--exclude": NONE,
    "-m": '"dev:python_modules"', "-p": '"dev:python_modules"', "-c": NONE,
}


def kind_of(names, mv, choices):
    if not choices and mv.startswith("{"):
        choices = mv.strip("{}").split(",")    # the choices in the metavar
    if choices:
        return "[" + ", ".join(f'"{c}"' for c in choices) + "]"
    if names[0].endswith("-report"):
        return DIRS
    if names[0] not in KINDS:
        raise SystemExit(f"mk_mypy.py: no kind for {names}: add it to KINDS")
    return KINDS[names[0]]


actions = [a for a in gen.argparse_dump(PKG, "mypy.main", "define_options", CHAN) if not a["positional"]]
# The inverses of flags (`--no-warn-unused-configs`) are hidden options, which the help names: offer them too.
inverse = {}
for a in actions:
    m = re.search(r"\(inverse: ([-\w, ]+)\)", a["help"] or "")
    if m:
        for n in m.group(1).split(","):
            inverse[n.strip()] = a["names"][-1]
        a["help"] = a["help"][:m.start()].rstrip()
for a in actions:
    if a["hidden"] and set(a["names"]) & set(inverse):
        a["hidden"] = False
        a["help"] = "inverse of " + inverse[next(n for n in a["names"] if n in inverse)]
    elif not a["help"] and a["names"][0].endswith("-report"):
        a["help"] = "write the " + a["names"][0][2:-7].replace("-", " ") + " report to DIR"

body = gen.emit_argparse(actions, kind_of, 12, f"""        args: [{K("python_files")}],
        args_if: #{{"-c": ["none"], "--command": ["none"]}},""")
codes = "\n".join(f'        #{{value: "{c}", desc: "{d[0].lower() + d[1:].rstrip(".")}"}},'
                  for c, d in [(c, d.replace('"', "'").replace("`", "'")) for c, d in info["codes"]])
open(gen.REPO + "/complete/dev/mypy.rhai", "w").write(f"""// mypy 2.3.1, from its argparse parser (`mypy --help`), with the inverses of its flags (`--no-strict-optional`),
// which the help names but doesn't list. Generated by scripts/gen/mk_mypy.py.

// This plugin's `MODULE:NAME` (a kind or sub_spec) by the module's path, whatever the source is called.
fn own(name) {{ sh::plugin_dir() + "/" + name }}

fn spec(cmd) {{
    #{{
{body}
    }}
}}

// The error codes, for `--enable-error-code` and `--disable-error-code`.
fn error_codes() {{
    [
{codes}
    ]
}}

fn kind(name, cur, words) {{
    switch name {{
        "error_codes" => error_codes(),
        _ => throw `unknown kind: ${{name}}`,
    }}
}}
""")
print("ok")
