"""Generates ../../completion/bio/cluster.rhai: sequence clustering (vsearch; cd-hit, cd-hit-est, cd-hit-2d,
cd-hit-est-2d, cd-hit-454), from their help at the pinned versions (see completion-todo.md).

    python3 scripts/gen/mk_cluster.py
"""
import os, re, sys
import gen
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import help2opts as h

VSEARCH = "vsearch=2.32.0"
CDHIT = "cd-hit=4.8.1"

K = lambda n: f'k("{n}")'
FA, FQ, SEQ = K("fasta"), K("fastq"), K("sequences")
L = lambda *xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"
out = []
def emit(s): out.append(s)

emit('''// Sequence clustering: vsearch, and cd-hit, cd-hit-est, cd-hit-2d, cd-hit-est-2d
// and cd-hit-454. Generated by scripts/gen/mk_cluster.py from the tools' own
// help (versions in completion-todo.md).

// This plugin's `MODULE:NAME` (a kind or sub_spec) by the module's path, whatever the source is called.
fn own(name) { sh::plugin_dir() + "/" + name }

fn k(name) { own("kinds:") + name }
''')

# ---------------- vsearch ----------------
# A command of vsearch is an option that names its input (`--cluster_fast FILENAME`), and the help lists the options
# of each command under it, so an option shows several times: it is listed once, with the description of its first
# showing, or the one below where that is about one command.
DESC = {
    "--abskew": "minimum abundance ratio",
    "--alignwidth": "width of alignments in alignment output",
    "--alnout": "filename for human-readable alignment output",
    "--chimeras": "output chimeric sequences to file",
    "--db": "reference database (FASTA, or UDB)",
    "--fastaout": "FASTA output filename",
    "--fastaout_discarded": "FASTA filename for discarded sequences",
    "--fastaout_rev": "FASTA filename for reverse sequences",
    "--fastqout": "FASTQ output filename",
    "--fastqout_discarded": "FASTQ filename for discarded sequences",
    "--fastq_qmaxout": "maximum base quality value for FASTQ output",
    "--label_suffix": "label to append to identifier in the output",
    "--log": "write messages, timing and memory info to file",
    "--fastaout_discarded_rev": "FASTA filename for discarded reverse sequences",
    "--fastq_maxdiffpct": "maximum percentage of different bases in overlap",
    "--fastq_trunclen": "truncate to given length (discard if shorter)",
    "--fastq_trunclen_keep": "truncate to given length (keep if shorter)",
    "--maxsize": "maximum abundance",
    "--minsize": "minimum abundance",
    "--msaout": "output multiple sequence alignments to FASTA file",
    "--notmatched": "FASTA file for non-matching sequences",
    "--output": "output file",
    "--relabel": "relabel sequences with this prefix string",
    "--sizeout": "write abundance annotation to output",
    "--strand": "plus or both strands",
    "--query_cov": "reject if fraction of query sequence aligned lower",
    "--tabbedout": "tab-separated output file",
    "--target_cov": "reject if fraction of target sequence aligned lower",
    "--uc": "filename for UCLUST-like output",
    "--wordlength": "length of words for matching or database index, 3-15",
    "--xsize": "strip abundance information in output",
}
# Options that take a value, but whose help names none.
ARG = {"--fastq_maxmergelen": "INT", "--fastq_minmergelen": "INT", "--fastq_minovlen": "INT",
       "--max_unmasked_pct": "REAL", "--min_unmasked_pct": "REAL", "--fastqout_discarded": "FILENAME"}
# The input of the commands that read FASTQ only.
FASTQ_IN = {"--fastq_chars", "--fastq_convert", "--fastq_eestats", "--fastq_eestats2", "--fastq_filter",
            "--fastq_join", "--fastq_mergepairs", "--fastq_stats", "--reverse"}
# The input of the commands that read FASTA or FASTQ.
SEQ_IN = {"--allpairs_global", "--chimeras_denovo", "--cluster_fast", "--cluster_size", "--cluster_smallmem",
          "--cluster_unoise", "--cut", "--derep_fulllength", "--derep_id", "--derep_prefix", "--derep_smallmem",
          "--fasta2fastq", "--fastx_filter", "--fastx_getseq", "--fastx_getseqs", "--fastx_getsubseq", "--fastx_mask",
          "--fastx_revcomp", "--fastx_subsample", "--fastx_syncpairs", "--fastx_uniques", "--makeudb_usearch",
          "--maskfasta", "--orient", "--rereplicate", "--scramble", "--search_exact", "--shuffle", "--sintax",
          "--sortbylength", "--sortbysize", "--uchime2_denovo", "--uchime3_denovo", "--uchime_denovo", "--uchime_ref",
          "--usearch_global"}
IDDEF = ('[#{value: "0", desc: "CD-HIT"}, #{value: "1", desc: "all differences"}, '
         '#{value: "2", desc: "internal gaps"}, #{value: "3", desc: "MBL"}, #{value: "4", desc: "BLAST"}]')


def vsearch_opts(text):
    """[(names, arg, desc)] of `vsearch --help`, each option once; a value name follows the name after one space."""
    rows, seen = [], set()
    for l in text.splitlines():
        m = re.match(r"^  (--\w+)(?: \| (-\w))?( \S+)?\s+(\S.*)$", l)
        if not m:
            continue
        name, short, arg, d = m.groups()
        arg = arg.strip() if arg else ARG.get(name, "")
        if name in seen:
            continue
        seen.add(name)
        d = re.sub(r"\s*\*.*$", "", d)                      # `(3) *`: a note on uchime2/3
        d = re.sub(r"\s*\([^()]*\)$", "", d)                # the default
        d = DESC.get(name, d)
        names = f"{short}, {name}" if short else name
        rows.append((names, arg, h.clean(d)))
    return rows


def vsearch_kind(name, arg):
    if name in FASTQ_IN:
        return FQ
    if name in SEQ_IN:
        return SEQ
    if "|" in arg:
        return L(*arg.split("|"))
    if name == "--iddef":
        return IDDEF
    if arg in ("FILENAME", "FN", "FILE") or name == "--clusters":
        return '"files"'
    if arg in ("INT", "REAL", "STRING", "REAL,...", "INT,INT,INT"):
        return '"none"'
    sys.exit(f"vsearch: no kind for {name} {arg}")


rows = vsearch_opts(gen.helptext(VSEARCH, "vsearch --help"))
values = {r[0].split(", ")[-1]: vsearch_kind(r[0].split(", ")[-1], r[1]) for r in rows if r[1]}
emit("fn vsearch() {\n    #{\n" + h.emit(rows, 12, values, '        args: ["none"],') + "\n    }\n}\n")

# ---------------- cd-hit ----------------
# `   -c\tsequence identity threshold, default 0.9`, the lines below it (a tab) say more.
CDHIT_PROGS = ["cd-hit", "cd-hit-est", "cd-hit-2d", "cd-hit-est-2d", "cd-hit-454"]
CDHIT_DESC = {
    "-B": "store sequences on the hard drive (no longer supported)",
    "-P": "input paired-end reads, with -i and -j",
    "-ap": "force sequences to align at their beginnings",
    "-bak": "write a backup cluster file",
    "-g": "cluster to the most similar cluster, not the first (slow)",
    "-h": "print this help",
    "-j": "input filename for R2 reads, if paired-end",
    "-j2": "input filename for R2 reads of db2, if paired-end",
    "-l": "throw away sequences shorter than this",
    "-p": "print alignment overlap in the .clstr file",
    "-r": "align both strands (1) or only +/+ (0)",
    "-sc": "sort clusters by size (number of sequences)",
    "-sf": "sort FASTA/FASTQ by cluster size (number of sequences)",
}
BOOL = {"-B", "-P", "-ap", "-bak", "-g", "-p", "-r", "-sc", "-sf"}


def cdhit_opts(prog, text):
    rows = []
    for l in text.splitlines():
        m = re.match(r"^   (-\S+(?:, -\S+)*)\t(.*)$", l)
        if not m:
            continue
        for name in m.group(1).split(", "):
            d = CDHIT_DESC.get(name) or re.split(r",? (?:default|1 or 0|required)\b|;", m.group(2))[0]
            d = d.replace(" in fasta format", "").replace(" if input are paired end (PE) files", ", if paired-end")
            d = d.replace("word_length", "word length").replace("band_width", "band width")
            d = d.replace("for the both", "for both")
            if name == "-h":
                arg, v = "", None
            elif name in BOOL:
                arg, v = "0|1", L("0", "1")
            elif name in ("-i", "-i2", "-j", "-j2"):
                arg, v = "FILE", SEQ if "est" in prog else FA
            elif name in ("-o", "-op"):
                arg, v = "FILE", '"files"'
            elif name == "-mask":
                arg, v = "LETTERS", '"none"'
            elif name in ("-match", "-mismatch", "-gap", "-gap-ext"):
                arg, v = "SCORE", '"none"'
            else:
                arg, v = "N", '"none"'
            rows.append((name, arg, h.clean(d), v))
    return rows


for prog in CDHIT_PROGS:
    rows = cdhit_opts(prog, gen.helptext(CDHIT, prog))
    values = {n: v for n, _, _, v in rows if v}
    b = h.emit([r[:3] for r in rows], 12, values, '        args: ["none"],\n        single_dash: true,')
    emit(f"fn {prog.replace('-', '_')}() {{\n    #{{\n{b}\n    }}\n}}\n")

emit("fn spec(cmd) {\n    switch cmd {")
for prog in ["vsearch"] + CDHIT_PROGS:
    emit(f'        "{prog}" => {prog.replace("-", "_")}(),')
emit("        _ => #{},\n    }\n}\n")
open(gen.REPO + "/completion/bio/cluster.rhai", "w").write("\n".join(out))
print("ok")
