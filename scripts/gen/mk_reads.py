# ---------------- porechop, NanoPlot, NanoFilt, NanoStat (argparse) ----------------
def kinds(table):
    def kind_of(names, mv, choices):
        if choices:
            return "[" + ", ".join(f'"{c}"' for c in choices) + "]"
        for n in names:
            if n in table:
                return table[n]
        return '"none"'
    return kind_of
for name, (mod, func), table, args in [
    ("porechop", ("porechop.porechop", "get_arguments"),
     {"-i": SEQ, "-o": '"files"', "-b": '"dirs"', "-v": L("0", "1", "2", "3")}, '["none"]'),
    # the input options take several files (`--fastq a.fq b.fq`): the words after the first are arguments
    ("NanoPlot", ("nanoplot.utils", "get_args"),
     {"-o": '"dirs"', "--fastq": FQ, "--fastq_rich": FQ, "--fastq_minimal": FQ, "--fasta": FA, "--bam": SAM,
      "--ubam": SAM, "--cram": SAM, "--summary": '"files"', "--pickle": '"files"', "--feather": '"files"'}, f"[{READS}]"),
    ("NanoFilt", ("nanofilt.utils", "get_args"), {"--logfile": '"files"', "-s": '"files"'}, f"[{FQ}]"),
    ("NanoStat", ("nanostat.NanoStat", "get_args"),
     {"-o": '"dirs"', "-n": '"files"', "--fastq": FQ, "--fasta": FA, "--bam": SAM, "--ubam": SAM, "--cram": SAM,
      "--summary": '"files"', "--feather": '"files"'}, f"[{READS}]"),
]:
    b = gen.emit_argparse(gen.argparse_dump(PIN[name], mod, func), kinds(table), 12, f"        args: {args},")
    emit(f"fn {name.lower()}() {{\n    #{{\n{b}\n    }}\n}}\n")

# ---------------- dispatch ----------------
names = ["fastp", "fastqc", "falco", "cutadapt", "trimmomatic", "trim_galore", "fastq_screen", "seqtk", "filtlong",
         "chopper", "nanoq", "rasusa", "porechop", "NanoPlot", "NanoFilt", "NanoStat"]
emit("fn spec(cmd) {\n    switch cmd {\n" + "".join(f'        "{n}" => {n.lower()}(),\n' for n in names) +
     "        _ => #{},\n    }\n}\n")
emit('''fn sub_spec(name, sub) {
    switch name {
        "seqtk" => seqtk_sub(sub),
        _ => (),
    }
}''')
