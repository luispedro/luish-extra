import help2opts as h

PIN = {
    "fastp": "fastp=1.3.7", "fastqc": "fastqc=0.12.1", "falco": "falco=2.0.2", "cutadapt": "cutadapt=5.2",
    "trimmomatic": "trimmomatic=0.41", "trim_galore": "trim-galore=2.3.0", "fastq_screen": "fastq-screen=0.16.0",
    "seqtk": "seqtk=1.5", "filtlong": "filtlong=0.3.1", "chopper": "chopper=0.14.1", "nanoq": "nanoq=0.10.0",
    "rasusa": "rasusa=5.1.0", "porechop": "porechop=0.2.4", "NanoPlot": "nanoplot=1.48.0",
    "NanoFilt": "nanofilt=2.8.0", "NanoStat": "nanostat=1.6.0",
}

K = lambda n: f'k("{n}")'
FA, FQ, SEQ, SAM, READS = K("fasta"), K("fastq"), K("sequences"), K("sam"), K("reads")
L = lambda *xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"
out = []
def emit(s): out.append(s)

def body(opts, values=None, args=None, extra="", indent=12):
    if not opts:
        return " " * (indent - 4) + f"args: {args}," + ("\n" + extra if extra else "")
    tail = ""
    if args:
        tail += " " * (indent - 4) + f"args: {args},\n"
    tail += extra
    return h.emit(opts, indent, values, tail.rstrip("\n"))

def fn(name, b):
    emit(f"fn {name}() {{\n    #{{\n{b}\n    }}\n}}\n")

def case(name, b):
    return f'        {name} => #{{\n{b}\n        }},'

emit('''// Read QC, trimming and filtering: fastp, fastqc, falco, cutadapt, trimmomatic,
// trim_galore, fastq_screen, seqtk, filtlong, chopper, nanoq, rasusa, porechop,
// NanoPlot, NanoFilt and NanoStat. Generated by scripts/gen/mk_reads.py from
// the tools' own `--help` or argparse parser (versions in completion-todo.md).

// This plugin's `MODULE:NAME` (a kind or sub_spec) by the module's path, whatever the source is called.
fn own(name) { sh::plugin_dir() + "/" + name }

fn k(name) { own("kinds:") + name }
''')

# ---------------- fastp ----------------
# `-i, --in1   read1 input file name (string [=])`: the type of the value, if any, is at the end.
def fastp_opts(text):
    rows = []
    for l in text.splitlines():
        m = re.match(r"^\s+((?:-\S, )?--\S+)\s+(.*)$", l)
        if not m or "DEPRECATED" in m.group(2):
            continue
        names, d = m.groups()
        t = re.search(r"\s*\((string|int|long|float) \[=[^\]]*\]\)$", d)
        arg = ""
        if t:
            arg = {"string": "STR", "int": "INT", "long": "INT", "float": "FLOAT"}[t.group(1)]
            d = d[:t.start()]
        rows.append((names, arg, h.clean(d)))
    return rows
FILES = {"-i", "-o", "-I", "-O", "--unpaired1", "--unpaired2", "--overlapped_out", "--failed_out", "--merged_out",
         "--adapter_fasta", "--filter_by_index1", "--filter_by_index2", "-j", "-h"}
fp = [(n, "FILE" if n.split(",")[0] in FILES else a, d) for n, a, d in fastp_opts(gen.helptext(PIN["fastp"], "fastp --help"))]
fn("fastp", body(fp, {"-i": FQ, "-I": FQ, "-o": '"files"', "-O": '"files"', "--adapter_fasta": FA,
                      "--umi_loc": L("index1", "index2", "read1", "read2", "per_index", "per_read")}, '["none"]'))

# ---------------- fastqc ----------------
# Blocks separated by blank lines, whose first line (or first two: `-c` then `--contaminants`) has the names.
def fastqc_opts(text):
    text = text.split("as follows:")[1].split("BUGS")[0]
    rows = []
    for b in re.split(r"\n\s*\n", text):
        lines = [l.split() for l in b.strip().splitlines()]
        if not lines or not lines[0][0].startswith("-"):
            continue
        names, desc = [], []
        for i, toks in enumerate(lines):
            if i == 1 and len(names) == 1 and toks[0].startswith("--"):
                names.append(toks.pop(0))
            while i == 0 and toks and toks[0].startswith("-"):
                names.append(toks.pop(0))
            desc += toks
        rows.append((names, h.clean(" ".join(desc))))
    return rows
FASTQC_ARG = {"--outdir": "DIR", "--java": "FILE", "--min_length": "INT", "--dup_length": "INT", "--format": "FORMAT",
              "--memory": "MB", "--threads": "INT", "--contaminants": "FILE", "--adapters": "FILE", "--limits": "FILE",
              "--kmers": "INT", "--dir": "DIR"}
fq = [(", ".join(n), FASTQC_ARG.get(n[-1], ""), d) for n, d in fastqc_opts(gen.helptext(PIN["fastqc"], "fastqc --help"))]
fn("fastqc", body(fq, {"-o": '"dirs"', "-d": '"dirs"', "-f": L("bam", "sam", "bam_mapped", "sam_mapped", "fastq")},
                  f'[{READS}]'))

# ---------------- falco ----------------
def falco_edit(opts):
    fix = {"-t, --threads": "INT", "-m, --mem": "SIZE", "--max-length": "SIZE"}   # --max-length takes one, not shown
    return [(n, fix.get(n, a), d) for n, a, d in opts]
fa = falco_edit(h.parse(gen.helptext(PIN["falco"], "falco --help")))
fn("falco", body(fa, {"-o": '"dirs"', "--stdin": L("fq", "sam", "fq:4", "fq:6", "sam:4", "sam:6")}, f'[{READS}]'))

# ---------------- cutadapt ----------------
ADAPTER = {"-a", "-g", "-b", "-A", "-G", "-B"}
def cutadapt_kind(names, mv, choices):
    if choices:
        return "[" + ", ".join(f'"{c}"' for c in choices) + "]"
    if ADAPTER & set(names):
        return K("cutadapt_adapter")
    return '"files"' if mv == "FILE" else '"none"'
b = gen.emit_argparse(gen.argparse_dump(PIN["cutadapt"], "cutadapt.cli", "get_argument_parser"), cutadapt_kind, 12,
                      f"        args: [{SEQ}],")
emit(f"fn cutadapt() {{\n    #{{\n{b}\n    }}\n}}\n")

# ---------------- trimmomatic ----------------
# No --help: the usage (`trimmomatic` with no arguments) and the steps of its TrimmerFactory.
usage = gen.helptext(PIN["trimmomatic"], "trimmomatic")
assert "-validatePairs" in usage and "-baseout" in usage, usage
common = [("-threads", "N", "number of threads"), ("-phred33", "", "qualities are Phred+33"),
          ("-phred64", "", "qualities are Phred+64"), ("-trimlog", "FILE", "log of the trimming of each read"),
          ("-summary", "FILE", "summary of the statistics"), ("-quiet", "", "print only errors"),
          ("-version", "", "print the version")]
pe = common + [("-validatePairs", "", "check that the names of the pairs match"),
               ("-basein", "FILE", "the first input file, whose name gives the second's"),
               ("-baseout", "FILE", "the base name of the four output files")]
step = K("trimmomatic_step")
emit(f'''fn trimmomatic() {{
    #{{
        commands: `
            PE  paired-end reads: two inputs, four outputs, then steps
            SE  single-end reads: an input, an output, then steps
        `,
        subs: #{{
            PE: #{{
{body(pe, {"-trimlog": '"files"', "-summary": '"files"', "-basein": FQ, "-baseout": '"files"', "-threads": '"none"'},
      f"[{FQ}, {FQ}, {step}]", '                single_dash: true,\n                args_if: #{"-basein": [' + step + ']},', 20)}
            }},
            SE: #{{
{body(common, {"-trimlog": '"files"', "-summary": '"files"', "-threads": '"none"'}, f"[{FQ}, {step}]",
      "                single_dash: true,", 20)}
            }},
        }},
    }}
}}
''')

# ---------------- trim_galore ----------------
tg = h.parse(gen.helptext(PIN["trim_galore"], "trim_galore --help"))
# -a2, in the help's examples, is accepted for --adapter2
tg = [("-a2, --adapter2" if n == "--adapter2" else n, a, d) for n, a, d in tg]
fn("trim_galore", body(tg, {"-o": '"dirs"', "--demux": '"files"', "--passthrough": FQ, "--output-format": L("fastq", "ubam"),
                            "-a": '"none"', "--adapter2": '"none"', "--basename": '"none"', "--fastqc_args": '"none"',
                            "--preserve-tags": '"none"'}, f'[{FQ}]'))

# ---------------- fastq_screen ----------------
fs = h.parse(gen.helptext(PIN["fastq_screen"], "fastq_screen --help"))
# the help's own slips: --minimap2 says BWA, and the description of --inverse is cut at "i.e."
fs = [(n, a, {"--minimap2": "specify extra parameters to be passed to minimap2",
              "--inverse": "inverts the --filter results"}.get(n, d)) for n, a, d in fs]
fn("fastq_screen", body(fs, {"--aligner": L("bowtie", "bowtie2", "bwa", "minimap2"), "--conf": '"files"',
                             "--outdir": '"dirs"', "--add_genome": '"none"', "--filter": '"none"'}, f"[{FQ}]"))

# ---------------- seqtk ----------------
# Most of seqtk's commands read standard input when it isn't a terminal, and print their usage only on one: run
# them under `script`, which gives them a pseudo-terminal.
def seqtk_help(sub):
    return gen.helptext(PIN["seqtk"], f'script -qec "seqtk {sub}" /dev/null')
top = gen.helptext(PIN["seqtk"], "seqtk")
cmds = [(m.group(1), m.group(2)) for m in re.finditer(r"^\s+(?:Command: )?(\w+)\s{2,}(.*)$", top, re.M)]
assert len(cmds) >= 20, cmds
w = max(len(c) for c, _ in cmds)
seqtk_args = {"subseq": f'[{SEQ}, "files"]', "mergepe": f"[{FQ}, {FQ}]", "split": f'["none", {SEQ}]',
              "mutfa": f'[{FA}, "files"]', "mergefa": f"[{FA}, {FA}]", "famask": f"[{FA}, {FA}]",
              "rename": f'[{SEQ}, "none"]'}
FASTA_ONLY = {"hety", "gc", "cutN", "gap", "listhet", "randbase"}
# options in the usage line but not listed under it
seqtk_fix = {("subseq", "-t"): ("", "TAB delimited output"), ("hety", "-t"): ("INT", "number of start positions in a window")}
seqtk_add = {"comp": [("-r", "FILE", "count only in the regions of a BED file"), ("-u", "", "count uppercase bases only")],
             "fqchk": [("-q", "INT", "quality threshold; 0 for the distribution of all qualities")],
             "gap": [("-l", "INT", "minimum length of a gap")]}
subs = []
for c, _ in cmds:
    o = [(n, *seqtk_fix.get((c, n), (a, d))) for n, a, d in h.parse(seqtk_help(c))] + seqtk_add.get(c, [])
    args = seqtk_args.get(c, f"[{FA}]" if c in FASTA_ONLY else f"[{SEQ}]")
    vals = {"seq": {"-M": '"files"'}, "comp": {"-r": K("bed")}}.get(c, {})
    subs.append(case(f'"{c}"', body(o, vals, args, indent=16)))
emit('fn seqtk() {\n    #{\n        commands: `\n' + "".join(f"            {c.ljust(w)}  {d}\n" for c, d in cmds) +
     '        `,\n        sub_spec: own("reads:seqtk"),\n    }\n}\n')
emit("fn seqtk_sub(sub) {\n    switch sub {\n" + "\n".join(subs) + "\n        _ => (),\n    }\n}\n")

# ---------------- filtlong ----------------
# `-t[int], --target_bases [int]`
fl = [(re.sub(r"\[\w+\]", "", n), a.strip("[]").upper(), d) for n, a, d in
      h.parse(gen.helptext(PIN["filtlong"], "filtlong --help"))]
fn("filtlong", body(fl, {"-a": FA, "-1": FQ, "-2": FQ}, f"[{FQ}]"))

