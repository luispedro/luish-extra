L = lambda *xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"
out = []
def emit(s): out.append(s)

def body(opts, values=None, args=None, extra="", indent=12):
    tail = ""
    if args:
        tail += " " * (indent - 4) + f"args: {args},\n"
    tail += extra
    if not opts:
        return tail.rstrip("\n")
    return h.emit(opts, indent, values, tail.rstrip("\n"))

def fn(name, b):
    emit(f"fn {name}() {{\n    #{{\n{b}\n    }}\n}}\n")

def case(name, b, indent=8, sep=" =>"):
    """A case of a switch, or with `sep=":"` an entry of a map."""
    p = " " * indent
    return f'{p}{name}{sep} #{{\n{b}\n{p}}},'

def argname(a):
    """`<BAM filename>` as BAM_FILENAME, `[=<FILE>]` as [=FILE]."""
    return re.sub(r"<([^<>]*)>", lambda m: m.group(1).replace(" ", "_").replace("/", "|").upper(), a)

def check(opts, kinds):
    """Every option with a value has a kind (a list of values, a kind, "files" or "none")."""
    for n, a, _ in opts:
        if a and not any(x in kinds for x in n.replace(",", " ").split()):
            sys.exit(f"no kind for {n} {a}")

