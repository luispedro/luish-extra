# `-F, --filter=FILTER` with the description on the next line: the value is written after a space, as the table has
# it. `sambamba SUB` with no arguments prints its help.
def sambamba_help(sub):
    t = gen.helptext(PIN["sambamba"], f"sambamba {sub}")
    t = re.sub(r"^(\s*(?:\w+:)?\s*(?:-\w, )?--[\w-]+)=(\S+)", r"\1 \2", t, flags=re.M)
    # the description is on the lines below the names: put it on the same line
    lines, out = t.splitlines(), []
    for l in lines:
        ind = len(l) - len(l.lstrip())
        if out and l.strip() and not re.match(r"^\s*(\w+:)?\s*-", l) and out[-1][0] is not None and ind > out[-1][0]:
            out[-1][1].append(l.strip())
            continue
        m = re.match(r"^(\s*(?:\w+:)?\s*)-", l)
        out.append([len(m.group(1)) if m else None, [l]])
    return "\n".join(p[0] + ("  " + " ".join(p[1:]) if len(p) > 1 else "") for _, p in out)

