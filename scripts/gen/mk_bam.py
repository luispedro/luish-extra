def sambamba_opts(sub, text=None):
    o = h.parse(text if text is not None else sambamba_help(sub))
    def desc(n, d):
        long = n.split()[-1]
        return SAMBAMBA_DESC.get((sub, long), SAMBAMBA_DESC.get(long, d))
    o = [(n, SAMBAMBA_FIX.get((sub, n), a), desc(n, d)) for n, a, d in o]
    check(o, SAMBAMBA_VALUES)
    return o

def vals_of(opts, table, fix=None):
    """The values of the options of `opts` that take one, from `table` and then `fix`."""
    names = {x for n, a, _ in opts if a for x in n.replace(",", " ").split()}
    return {k: v for k, v in (table | (fix or {})).items() if k in names}

