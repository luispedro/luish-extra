"""Generates ../../complete/dev/pytest.rhai for pytest, with pytest-xdist and pytest-cov (the plugins most projects
use), from its argparse parser at pinned versions (pytest_parser.py).

    python3 scripts/gen/mk_pytest.py
"""
import re
import gen
from gen import h

PKG = "pytest=9.1.1 pytest-xdist=3.8.0 pytest-cov=7.1.0"
CHAN = "-c conda-forge"
K = lambda n: f'"@extra-complete/dev/kinds:{n}"'
LEVELS = '["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"]'
NONE, FILES, DIRS = '"none"', '"files"', '"dirs"'

# The values of the options that take one and have no choices, by their first name. An option that is not here makes
# the generator stop, so that a new version's options are looked at.
KINDS = {
    "-k": NONE, "-m": K("pytest_markers"), "--maxfail": NONE,
    "-W": '["default", "error", "ignore", "always", "module", "once"]',
    "--max-warnings": NONE, "--ignore": FILES, "--ignore-glob": NONE, "--deselect": K("pytest_tests"),
    "--confcutdir": DIRS, "-c": FILES, "--rootdir": DIRS, "--basetemp": DIRS, "--durations": NONE,
    "--durations-min": NONE, "-p": NONE, "--debug": FILES, "-o": '"@extra-complete/dev/pytest:ini"',
    "--verbosity": NONE, "-r": '["fE", "a", "A", "N", "f", "E", "s", "x", "X", "p", "P", "w"]', "--pdbcls": NONE,
    "--junitxml": FILES, "--junitprefix": NONE, "--doctest-glob": NONE, "--cache-show": NONE,
    "--log-level": LEVELS, "--log-cli-level": LEVELS, "--log-file-level": LEVELS, "--log-format": NONE,
    "--log-date-format": NONE, "--log-cli-format": NONE, "--log-cli-date-format": NONE, "--log-file": FILES,
    "--log-file-format": NONE, "--log-file-date-format": NONE, "--log-auto-indent": '["true", "false", "on", "off"]',
    "--log-disable": NONE,
    # pytest-xdist
    "-n": '["auto", "logical"]', "--maxprocesses": NONE, "--max-worker-restart": NONE, "--tx": NONE, "--px": NONE,
    "--rsyncdir": DIRS, "--rsyncignore": NONE, "--testrunuid": NONE, "--maxschedchunk": NONE,
    # pytest-cov
    "--cov": DIRS,
    "--cov-report": '["term", "term-missing", "term:skip-covered", "annotate", "html", "xml", "json", "lcov", '
                    '"markdown", "markdown-append"]',
    "--cov-config": FILES, "--cov-fail-under": NONE, "--cov-precision": NONE, "--cov-context": '["test"]',
}


# Descriptions that the help's first sentence doesn't give well.
DESC = {
    "-c": "load configuration from FILE instead of the implicit configuration files",
    "-o": "override a configuration option (NAME=VALUE)",
    "--pdbcls": "custom interactive Python debugger for --pdb (modulename:classname)",
    "--lfnf": "with --lf, what to run when there are no known failures",
    "-n": "number of workers (auto: one per CPU, logical: per logical CPU)",
    "--maxprocesses": "maximum number of workers with --numprocesses",
    "--loadscope-reorder": "reorder tests by number of tests per scope with --dist loadscope",
    "--no-loadscope-reorder": "don't reorder tests with --dist loadscope",
    "--px": "add a proxy gateway to pass to test execution environments",
}


def kind_of(names, mv, choices):
    if choices:
        return "[" + ", ".join(f'"{c}"' for c in choices) + "]"
    if names[0] not in KINDS:
        raise SystemExit(f"mk_pytest.py: no kind for {names}: add it to KINDS")
    return KINDS[names[0]]


actions = [a for a in gen.argparse_dump(PKG, "pytest_parser.py", "parser", CHAN) if not a["positional"]]
for a in actions:
    if a["names"] and a["names"][0] in DESC:
        a["help"] = DESC[a["names"][0]]
body = gen.emit_argparse(actions, kind_of, 12, f"""        args: [{K("pytest_tests")}],
        args_if: #{{"--doctest-modules": [{K("pytest_modules")}], "--pyargs": ["dev:python_modules"]}},""")
ini = gen.dump(PKG, "pytest_parser.py", "", CHAN)
rows = "\n".join(f'        #{{value: "{n}=", desc: "{re.sub(r"[:,]? one of$", "", h.clean(d)).rstrip(':').replace(chr(34), chr(39))}", suffix: ""}},' for n, d in ini)
open(gen.REPO + "/complete/dev/pytest.rhai", "w").write(f"""// pytest 9.1.1, with the options of pytest-xdist 3.8.0 and pytest-cov 7.1.0, from its argparse parser (`pytest
// --help`). The arguments are test files and directories, and the tests in a file (`test_x.py::TestY::test_z`).
// Generated by scripts/gen/mk_pytest.py.

fn spec(cmd) {{
    #{{
{body}
    }}
}}

// The configuration options, for `-o NAME=VALUE`.
fn ini() {{
    [
{rows}
    ]
}}

fn kind(name, cur, words) {{
    switch name {{
        "ini" => ini(),
        _ => throw `unknown kind: ${{name}}`,
    }}
}}
""")
print("ok")
