"""Generates ../../completion/bio/asm.rhai: assembly and annotation (spades.py, metaspades.py, megahit, flye, quast,
metaquast, busco, prodigal, prokka, bakta, barrnap), from their --help or argparse parser at the pinned versions (see
completion-todo.md).

    python3 scripts/gen/mk_asm.py
"""
import os, re, sys
import gen
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import help2opts as h

PIN = {
    "spades": "spades=4.3.0", "megahit": "megahit=1.2.9", "flye": "flye=2.9.6", "prodigal": "prodigal=2.6.3",
    "prokka": "prokka=1.15.6", "bakta": "bakta=1.12.1", "busco": "busco=6.1.0", "barrnap": "barrnap=1.10.6",
    # quast 5.3.0 imports distutils, which Python 3.12 dropped
    "quast": "quast=5.3.0 python=3.11",
}

K = lambda n: f'k("{n}")'
FA, FQ, SEQ, SAM, BAM, READS, HMM = K("fasta"), K("fastq"), K("sequences"), K("sam"), K("bam"), K("reads"), K("hmm")
L = lambda *xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"
FILES, DIRS, NONE = '"files"', '"dirs"', '"none"'
out = []
def emit(s): out.append(s)

def check(opts, kinds):
    """Every option with a value has a kind (a list of values, a kind, "files" or "none")."""
    for n, a, _ in opts:
        if a and not any(x in kinds for x in n.replace(",", " ").split()):
            sys.exit(f"no kind for {n} {a}")

def body(opts, values, args, extra="", indent=12):
    check(opts, values)
    tail = " " * (indent - 4) + f"args: {args},\n" + extra
    return h.emit(opts, indent, values, tail.rstrip("\n"))

def fn(name, b):
    emit(f"fn {name}() {{\n    #{{\n{b}\n    }}\n}}\n")

def argname(a):
    """`<output_dir>` as OUTPUT_DIR, `<int> [<int> ...]` as INT, `<int,int,...>` as INTS, `[X]` as X."""
    a = a.split(" [")[0]
    def name(m):
        x = m.group(1)
        if re.search(r",\.\.\.?$", x):
            return x.split(",")[0].upper() + "S"
        return x.replace(" ", "_").upper()
    return re.sub(r"[<\[]([^<>\[\]]*)[>\]]", name, a)

def tidy(opts, fix={}):
    """The descriptions without the trailing comma of a cut sentence, and those of `fix` instead of the help's."""
    return [(n, a, fix.get(n, d.rstrip(","))) for n, a, d in opts]

def kinds(table):
    """kind_of for gen.emit_argparse: the choices, or the kind in `table` by one of the option's names."""
    def kind_of(names, mv, choices):
        if choices:
            return L(*choices)
        for n in names:
            if n in table:
                return table[n]
        sys.exit(f"no kind for {names} {mv}")
    return kind_of

emit('''// Assembly and annotation: spades.py, metaspades.py, megahit, flye, quast,
// metaquast, busco, prodigal, prokka, bakta and barrnap. Generated by
// scripts/gen/mk_asm.py from the tools' own `--help` or argparse parser
// (versions in completion-todo.md).

// This plugin's `MODULE:NAME` (a kind or sub_spec) by the module's path, whatever the source is called.
fn own(name) { sh::plugin_dir() + "/" + name }

fn k(name) { own("kinds:") + name }
''')

# ---------------- spades.py, metaspades.py ----------------
# `--pe-1 <#> <filename>`: the number of the library, then the file. The table has the number as the option's value,
# and the file is completed as an argument (spades.py has no arguments of its own).
def spades_opts(text):
    rows = []
    for n, a, d in h.parse(text):
        m = re.match(r"^<#> <(\w+)> (.*)$", d)
        if m:
            a, d = "<#>", m.group(2).replace("<#>", "N")
        a = {"<last or all>": "WHEN", "<33 or 64>": "OFFSET"}.get(a, a)
        rows.append((n, argname(a).replace("#", "N"), d))
    return tidy(rows)
READ_OPTS = ["--12", "-1", "-2", "-s", "--merged", "--sanger", "--pacbio", "--nanopore"]
def spades_values(opts):
    v = {n: READS for n in READ_OPTS}
    v.update({"-o": DIRS, "--tmp-dir": DIRS, "--custom-hmms": DIRS, "--dataset": FILES,
              "--trusted-contigs": FA, "--untrusted-contigs": FA, "--checkpoints": L("last", "all"),
              "--restart-from": L("ec", "as", "mc", "last"), "--phred-offset": L("33", "64"),
              "--cov-cutoff": L("auto", "off"), "--grid-engine": L("slurm", "local", "mpi", "save_yaml")})
    for n, a, _ in opts:
        n = n.split(", ")[0]
        if n not in v and a:
            assert a in ("N", "INT", "FLOAT", "STRING"), (n, a)    # library numbers, numbers, the grid's settings
            v[n] = NONE
    return v
for name, prog in [("spades", "spades.py"), ("metaspades", "metaspades.py")]:
    o = spades_opts(gen.helptext(PIN["spades"], f"{prog} --help"))
    fn(name, body(o, spades_values(o), f"[{READS}]"))

# ---------------- megahit ----------------
mh = [(n, argname(a), d) for n, a, d in h.parse(gen.helptext(PIN["megahit"], "megahit --help"))]
# descriptions over several lines, which the table would cut
mh = tidy(mh, {"-1": "paired-end #1 files (FASTA/Q, comma-separated), paired with those of -2",
               "-2": "paired-end #2 files (FASTA/Q, comma-separated), paired with those of -1",
               "--k-list": "comma-separated list of k-mer sizes (odd, 15-255, steps <= 28)",
               "--disconnect-ratio":
                   "disconnect unitigs whose depth is below this ratio of their and their siblings' total",
               "--low-local-ratio":
                   "remove unitigs whose depth is below this ratio of the mean depth of their neighbours",
               "--presets": "override a group of parameters: meta-sensitive, meta-large",
               "--mem-flag": "SdBG builder memory mode: 0 minimum, 1 moderate, others all of --memory",
               "-t, --num-cpu-threads": "number of CPU threads"})
mhv = {"-1": READS, "-2": READS, "--12": READS, "-r": READS, "-o": DIRS, "--tmp-dir": DIRS,
       "--presets": L("meta-sensitive", "meta-large")}
mhv.update({n.split(",")[0]: NONE for n, a, _ in mh if a and n.split(",")[0] not in mhv})
fn("megahit", body(mh, mhv, '["none"]'))

# ---------------- flye (argparse) ----------------
# The read options take several files (`--nano-hq a.fq b.fq`): the words after the first are arguments.
STAGES = ["configure", "assembly", "consensus", "repeat", "contigger", "finalize", "polishing"]
fl = gen.argparse_dump(PIN["flye"], "flye.main", "main")
for a in fl:
    a["help"] = (a["help"] or "").replace("odler", "older").replace("%%", "%")
fly = {n: READS for n in ["--pacbio-raw", "--pacbio-corr", "--pacbio-hifi", "--nano-raw", "--nano-corr", "--nano-hq",
                          "--subassemblies"]}
fly.update({"-o": DIRS, "--polish-target": FA, "--resume-from": L(*STAGES), "--stop-after": L(*STAGES)})
fly.update({n: NONE for n in ["-g", "-t", "-i", "-m", "--asm-coverage", "--hifi-error", "--read-error",
                              "--extra-params"]})
emit(f"fn flye() {{\n    #{{\n{gen.emit_argparse(fl, kinds(fly), 12, f'        args: [{READS}],')}\n    }}\n}}\n")

# ---------------- quast.py, metaquast.py ----------------
# `-o  --output-dir  <dirname>       Directory ...`: a short name, a long one or both, then the value, then the
# description after a gap (a space after the value); the lines below that start with spaces and no `-` continue it.
def quast_opts(text):
    rows = []
    for l in text.splitlines():
        m = re.match(r'^(-\w)?\s*(--[\w-]+)?\s*((?:\[type:\])?<[^>]*>|"[^"]*")?(?:(?<=[>"])\s+|\s{2,})(\S.*)$', l)
        if not m or not (m.group(1) or m.group(2)) or not l.lstrip().startswith("-"):
            continue
        names = ", ".join(x for x in m.group(1, 2) if x)
        a = m.group(3) or ""
        a = "LABELS" if a.startswith('"') else argname(a.replace("[type:]", "")).replace(",...", "S")
        rows.append((names, a, h.clean(m.group(4))))
    return rows
def quast_fix(opts):
    # --k-mer-size takes a number, which the help doesn't show
    return [(n, "INT" if n == "--k-mer-size" else a, d) for n, a, d in opts]
quast_values = {"-o": DIRS, "-r": FA, "-g": FILES, "--operons": FILES, "-a": L("none", "one", "all"),
                "--plots-format": L("emf", "eps", "pdf", "png", "ps", "raw", "rgba", "svg", "svgz"),
                "-1": FQ, "-2": FQ, "--pe12": FQ, "--mp1": FQ, "--mp2": FQ, "--mp12": FQ, "--single": FQ,
                "--pacbio": READS, "--nanopore": READS, "--ref-sam": SAM, "--ref-bam": BAM, "--sam": SAM,
                "--bam": BAM, "--sv-bedpe": K("bed"), "--references-list": FILES, "--blast-db": FILES}
for name, prog in [("quast", "quast.py"), ("metaquast", "metaquast.py")]:
    o = tidy(quast_fix(quast_opts(gen.helptext(PIN["quast"], f"{prog} --help"))))
    assert len(o) > 70, len(o)
    v = dict(quast_values)
    v.update({n.split(",")[0]: NONE for n, a, _ in o if a and not any(x in v for x in n.split(", "))})
    fn(name, body(o, v, f"[{FA}]"))

# ---------------- busco (argparse) ----------------
bu = gen.argparse_dump(PIN["busco"], "busco.run_BUSCO", "_parse_args")
for a in bu:
    if (a["metavar"] or "").startswith('"'):     # "--PARAM1=VALUE1,--PARAM2=VALUE2"
        a["metavar"] = "PARAMS"
    if a["names"] == ["--long"]:
        a["help"] = "optimization mode of Augustus self-training (slow)"
DATASETS = L("odb10", "odb12", "odb12.2")
buv = {"-i": FA, "-l": K("busco_lineage"), "--download": K("busco_download"),
       "-m": L("genome", "geno", "transcriptome", "tran", "proteins", "prot"), "--config": FILES,
       "--download_path": DIRS, "--out_path": DIRS, "--plot": DIRS, "--datasets_version": DATASETS,
       "--list-datasets": DATASETS}
buv.update({n: NONE for n in ["-o", "--augustus_parameters", "--augustus_species", "-c", "--contig_break",
                              "--download_base_url", "-e", "--limit", "--metaeuk_parameters",
                              "--metaeuk_rerun_parameters"]})
emit(f"fn busco() {{\n    #{{\n{gen.emit_argparse(bu, kinds(buv), 12, '        args: [\"none\"],')}\n    }}\n}}\n")

# ---------------- prodigal ----------------
# `-a:  Write protein translations to the selected file.`, and the usage line has the value names.
pt = gen.helptext(PIN["prodigal"], "prodigal -h")
usage = dict(re.findall(r"\[(-\w) (\w+)\]", pt))
po = []
for m in re.finditer(r"^\s+(-\w):\s+(.*(?:\n\s{14,}\S.*)*)", pt, re.M):
    n, d = m.group(1), " ".join(m.group(2).split())
    a = usage.get(n, "").upper()
    po.append((n, a, h.clean(d)))
po = tidy(po, {"-c": "closed ends: don't let genes run off the edges",
               "-t": "write a training file, or read it if it exists"})
assert len(po) == 15, po
fn("prodigal", body(po, {"-a": FILES, "-d": FILES, "-o": FILES, "-s": FILES, "-t": FILES, "-i": FA,
                         "-f": L("gbk", "gff", "sco"), "-p": L("single", "meta"), "-g": NONE}, '["none"]'))

# ---------------- prokka ----------------
# `--dbdir [X]   Prokka database root folders (default '/the/env/db')`: the defaults, which are the machine's, go.
pk = [(n, argname(a).replace("N.N", "NUM"), d.replace("prokka database", "Prokka database"))
      for n, a, d in h.parse(gen.helptext(PIN["prokka"], "prokka --help"))]
pkv = {"--dbdir": DIRS, "--outdir": DIRS, "--kingdom": L("Archaea", "Bacteria", "Mitochondria", "Viruses"),
       "--gram": L("neg", "pos"), "--proteins": FILES, "--hmms": HMM, "--prodigaltf": FILES,
       "--gffver": L("1", "2", "3")}
pkv.update({n: NONE for n, a, _ in pk if a and n not in pkv})
fn("prokka", body(pk, pkv, f"[{FA}]"))

# ---------------- bakta (argparse) ----------------
ba = gen.argparse_dump(PIN["bakta"], "bakta.utils", "parse_arguments")
bav = {"--db": DIRS, "--output": DIRS, "--tmp-dir": DIRS, "--prodigal-tf": FILES, "--replicons": FILES,
       "--regions": FILES, "--proteins": FILES, "--hmms": HMM}
bav.update({n: NONE for n in ["--min-contig-length", "--prefix", "--genus", "--species", "--strain", "--plasmid",
                              "--locus", "--locus-tag", "--threads"]})
emit(f"fn bakta() {{\n    #{{\n{gen.emit_argparse(ba, kinds(bav), 12, f'        args: [{FA}],')}\n    }}\n}}\n")

# ---------------- barrnap ----------------
bt = gen.helptext(PIN["barrnap"], "barrnap --help")
br = h.parse(bt)
# `--rrna  Find rRNA, disable with --no-rrna`: the --no- options aren't in the table
br += [(f"--no-{x}", "", f"don't find {x[:-3]}{x[-3:].upper()}") for x in ["rrna", "trna", "ncrna", "mrna"]
       if f"--no-{x}" in bt]
br = [(n, a, d.replace("tagsn", "tags").replace("FInd ALL", "find all").replace("idenitfy", "identify"))
      for n, a, d in br]
fn("barrnap", body(br, {"--dbdir": DIRS, "--kingdom": L("bac", "arc", "fun"), "--outseq": FILES, "--gcode": NONE,
                        "--threads": NONE, "--evalue": NONE}, f"[{SEQ}]"))

# ---------------- dispatch ----------------
progs = {"spades.py": "spades", "metaspades.py": "metaspades", "megahit": "megahit", "flye": "flye",
         "quast": "quast", "quast.py": "quast", "metaquast": "metaquast", "metaquast.py": "metaquast",
         "busco": "busco", "prodigal": "prodigal", "prokka": "prokka", "bakta": "bakta", "barrnap": "barrnap"}
emit("fn spec(cmd) {\n    switch cmd {\n" + "".join(f'        "{p}" => {f}(),\n' for p, f in progs.items()) +
     "        _ => #{},\n    }\n}")
open(gen.REPO + "/completion/bio/asm.rhai", "w").write("\n".join(out) + "\n")
print("written")
